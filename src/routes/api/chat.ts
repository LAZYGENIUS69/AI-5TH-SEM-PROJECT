import {
  createLovableAiGatewayRunIdFetch,
  getLovableAiGatewayResponseHeaders,
  getLovableAiGatewayRunId,
  withLovableAiGatewayRunIdHeader,
} from "@/lib/ai-gateway.server";
import { createOpenAI } from "@ai-sdk/openai";
import { createFileRoute } from "@tanstack/react-router";
import { convertToModelMessages, streamText, type UIMessage } from "ai";

type ChatRequestBody = {
  messages?: unknown;
  context?: unknown;
  farm?: unknown;
};

export const Route = createFileRoute("/api/chat")({
  server: {
    handlers: {
      POST: async ({ request }) => {
        const body = (await request.json()) as ChatRequestBody;
        const messages = body.messages;
        if (!Array.isArray(messages)) {
          return new Response("Messages are required", { status: 400 });
        }

        const key = process.env["LOVABLE_API_KEY"];
        if (!key) {
          return new Response("AI is not configured for this app yet.", { status: 500 });
        }

        const contextBlock = typeof body.context === "string" ? body.context : "";
        const farmBlock = typeof body.farm === "string" ? body.farm : "";

        const system = `You are AgriSense, an agronomy advisor for Indian farmers and field agronomists.

Rules:
- Answer using the RETRIEVED CONTEXT as your primary evidence. Cite it inline as [1], [2] matching the numbered passages.
- If the context does not cover the question, say so plainly in one line, then give careful general agronomic guidance clearly marked as general advice.
- Be practical and specific: give rates (kg/ha, g/L), timing, and the observable signs to check.
- Keep answers under 220 words. Use short paragraphs or tight bullet lists.
- Use simple language a farmer can act on. Metric units only.
- Never invent chemical names, brand names, or government scheme details.

FARM PROFILE
${farmBlock || "Not provided."}

RETRIEVED CONTEXT
${contextBlock || "No indexed passage matched this question."}`;

        const initialRunId = getLovableAiGatewayRunId(request);
        const runIdFetch = createLovableAiGatewayRunIdFetch(initialRunId);
        const lovable = createOpenAI({
          baseURL: "https://ai.gateway.lovable.dev/v1",
          apiKey: key,
          headers: { "Lovable-API-Key": key, "X-Lovable-AIG-SDK": "vercel-ai-sdk" },
          fetch: runIdFetch.fetch,
        });

        const result = streamText({
          model: lovable.responses("openai/gpt-6-astra"),
          system,
          messages: await convertToModelMessages(messages as UIMessage[]),
          providerOptions: {
            openai: {
              forceReasoning: true,
              reasoningEffort: "low",
              reasoningSummary: "auto",
              store: false,
              include: ["reasoning.encrypted_content"],
            },
          },
        });

        return withLovableAiGatewayRunIdHeader(
          result.toUIMessageStreamResponse({
            originalMessages: messages as UIMessage[],
            headers: getLovableAiGatewayResponseHeaders(undefined, {
              ...(initialRunId ? { "X-Lovable-AIG-Run-ID": initialRunId } : {}),
            }),
          }),
          runIdFetch,
        );
      },
    },
  },
});
